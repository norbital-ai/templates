// ---------- arithmetic ----------
const EPS = 1e-7;
/** strip binary noise so a decimal .5 stays .5 */
const norm = (x: number) => Math.round(x * 1e6) / 1e6;
/** CUR art.3: under 50銭 dropped, 50銭 and over up (half-up to the yen). */
export const yen = (x: number) => Math.sign(x) * Math.floor(Math.abs(norm(x)) + 0.5 + EPS);
/** KK note ① / EI rounding: deduction from wages drops a fraction of 50銭 or less, rounds more than 50銭 up. */
export const halfDown = (x: number) => {
	const v = norm(x);
	const f = v - Math.floor(v);
	return f > 0.5 + EPS ? Math.ceil(v) : Math.floor(v);
};
const trunc = (x: number) => Math.floor(norm(x) + EPS);

// ---------- dates ----------
const D = (iso: string) => Date.UTC(+iso.slice(0, 4), +iso.slice(5, 7) - 1, +iso.slice(8, 10));
const iso = (t: number) => new Date(t).toISOString().slice(0, 10);
const DAY = 86_400_000;
export const addDays = (d: string, n: number) => iso(D(d) + n * DAY);
const daysIn = (p: string) => new Date(Date.UTC(+p.slice(0, 4), +p.slice(5, 7), 0)).getUTCDate();
export const monthEnd = (p: string) => `${p}-${String(daysIn(p)).padStart(2, '0')}`;
export const addMonths = (p: string, n: number) => {
	const m = +p.slice(0, 4) * 12 + (+p.slice(5, 7) - 1) + n;
	return `${Math.floor(m / 12)}-${String((m % 12) + 1).padStart(2, '0')}`;
};
const dow = (d: string) => new Date(D(d)).getUTCDay(); // 0 Sunday
/** the birthday of age n (29 Feb in a common year: 1 Mar) */
const birthday = (birth: string, n: number) => {
	const y = +birth.slice(0, 4) + n;
	const md = birth.slice(5);
	const leap = (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0;
	return md === '02-29' && !leap ? `${y}-03-01` : `${y}-${md}`;
};
/** 年齢計算ニ関スル法律: age n is attained on the day before the n-th birthday */
const attains = (birth: string, n: number) => addDays(birthday(birth, n), -1);
const daysOf = (p: string) =>
	Array.from({ length: daysIn(p) }, (_, i) => `${p}-${String(i + 1).padStart(2, '0')}`);
const minutes = (hhmm: string) => +hhmm.slice(0, 2) * 60 + +hhmm.slice(3, 5);

