/** 月額表 by 社会保険料等控除後の給与等の金額 A. DEFAULT: an amount the table computes with a fraction is truncated. */
export function monthlyTableTax(A: number, column: 'KOU' | 'OTSU', dependants: number): number {
	if (A < 105_000) return column === 'OTSU' ? trunc((A * 3.063) / 100) : 0;
	const k = Math.min(dependants, 7);
	let v: number;
	if (A < 740_000) {
		const row = MONTHLY_2026.find((r) => A >= r[0]! && A < r[1]!)!;
		v = column === 'OTSU' ? row[10]! : row[2 + k]!;
	} else if (column === 'OTSU') {
		v =
			A === 1_710_000
				? 655_400
				: A < 1_710_000
					? 259_200 + ((A - 740_000) * 40.84) / 100
					: 655_400 + ((A - 1_710_000) * 45.945) / 100;
	} else {
		const [anchor, amounts, pct] = [...MONTHLY_KOU_TOP].reverse().find(([a]) => A >= a)!;
		v = amounts[k]! + ((A - anchor) * pct) / 100;
	}
	// 月額表 (七) note: each dependant beyond seven takes 1,610 off the seven-dependant amount (甲 only)
	if (column === 'KOU' && dependants > 7) v -= 1_610 * (dependants - 7);
	return Math.max(0, trunc(v));
}
