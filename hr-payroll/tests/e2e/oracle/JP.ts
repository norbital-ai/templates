/** LSA arts.32, 35, 37; PREM: classify each minute worked in the period (week = Sunday–Saturday, DEFAULT absent a
 *  work-rules week; Sunday is the 法定休日, Saturday a 所定休日). */
function classify(s: Scenario, employed: (d: string) => boolean): Minutes {
	const e = s.employee;
	const start = `${s.period}-01`;
	const end = monthEnd(s.period);
	const out: Minutes = { INLAW: 0, OT: 0, OT60: 0, HOL: 0, REST: 0, NIGHT: 0 };
	const unpaid = new Set(s.time.unpaidLeaveDays);
	const paid = new Set(s.time.paidLeaveDays);
	const explicit = new Map(s.time.work.map((w) => [w.date, w]));
	let week = 0;
	let month = 0;
	for (let d = addDays(start, -dow(start)); d <= end; d = addDays(d, 1)) {
		const wd = dow(d);
		if (wd === 0) week = 0;
		const inPeriod = d >= start;
		if (!employed(d) || unpaid.has(d) || paid.has(d)) continue;
		const w = explicit.get(d);
		let spans: [number, number][];
		if (w) {
			const a = minutes(w.start);
			const b = minutes(w.end);
			spans =
				w.breakMinutes > 0
					? [
							[a, 720],
							[720 + w.breakMinutes, b]
						]
					: [[a, b]];
		} else if (wd >= 1 && wd <= 5) {
			const h = e.dailyHours * 60;
			spans =
				h <= 360
					? [[540, 540 + h]]
					: [
							[540, 720],
							[780, 780 + h - 180]
						];
		} else continue;
		const scheduled = wd >= 1 && wd <= 5 ? e.dailyHours * 60 : 0;
		let day = 0;
		for (const [a, b] of spans)
			for (let m = a; m < b; m++) {
				const night = (m >= 1320 && m < 1740) || m < 300; // LSA art.37(4): 22:00–05:00
				let kind: keyof Minutes | 'ORD';
				if (wd === 0) kind = 'HOL';
				else if (day < scheduled) {
					kind = 'ORD';
					week++;
				} else if (day < 480 && week < 2400) {
					// within 8h/40h: no §37 premium. DEFAULT (JP-OT-02 owner rule): 100% on a scheduled day (法内残業), 125% on a
					// 所定休日 (Saturday); neither is statutory overtime, so neither enters the 60-hour count
					kind = wd === 6 ? 'REST' : 'INLAW';
					week++;
				} else kind = 'OT'; // beyond 8h a day or 40h a week
				day++;
				if (!inPeriod) continue;
				if (kind === 'OT') {
					if (month >= 3600) kind = 'OT60'; // LSA art.37(1) proviso: beyond 60h in the month, 50%
					month++;
				}
				if (kind !== 'ORD') out[kind]++;
				if (night) out.NIGHT++;
			}
	}
	return out;
}

