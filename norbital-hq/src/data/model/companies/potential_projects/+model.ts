import { model } from '@norbital-ai/bolt';

const columns = ['summary', 'rank', 'status', 'company'] as const;

/**
 * One app the delivery team could build for a company, in one short sentence ("Driver dispatch board with proof-of-delivery
 * photos"). `research_lead` proposes 3–5 with the outreach prompt and records its `prompt_version`; a person keeps or
 * discards each (or writes one: no version). A cohort's `{{potential_projects}}` renders the kept ones by `rank`.
 */
export default model('potential_projects', {
	description:
		'A proposed initiative or product fit for a company, generated by research or written by hand.',
	icon: 'lucide:lightbulb',
	record_label: 'record.summary',
	fields: {
		company: { kind: 'ref', to: 'companies', inverse: 'potential_projects', on_delete: 'cascade' },
		summary: { kind: 'text' },
		rank: { kind: 'int', min: 1, default: 1 },
		status: { kind: 'enum', values: ['proposed', 'kept', 'discarded'], default: 'proposed' },
		prompt_version: { kind: 'int', min: 1, optional: true }
	},
	indexes: { by_company: { on: ['company', 'rank'] } },
	outputs: { default: { fields: 'all', company: { fields: ['name'] } } },
	create: { fields: [...columns, 'prompt_version'] },
	update: { fields: columns },
	delete: {}
});
